import fs from "node:fs";
import path from "node:path";

function deep(a, b) {
  for (const k of Object.keys(b)) {
    if (b[k] && typeof b[k] === "object" && !Array.isArray(b[k])) {
      a[k] = a[k] && typeof a[k] === "object" ? a[k] : {};
      deep(a[k], b[k]);
    } else a[k] = b[k];
  }
  return a;
}
function merge(file, extra) {
  const p = path.join("messages", file);
  const base = JSON.parse(fs.readFileSync(p, "utf8"));
  fs.writeFileSync(p, JSON.stringify(deep(base, extra), null, 2) + "\n");
}

